"""
label_generator.py
Wraps the bundled zint.exe to render GS1 barcode symbols, then composes
the final label image (header text, barcode, human-readable data text for
2D symbols, footer text) sized to the requested physical label dimensions.
"""

import os
import subprocess
import sys
import tempfile

from PIL import Image, ImageDraw, ImageFont

# Zint can render a very wide intermediate bitmap for long GS1 element
# strings at a fine X-dimension/high DPI (this is expected -- our own
# shrink-toward-minimum logic in generate_barcode_image() then scales it
# down to fit the label). That intermediate bitmap is locally generated by
# our own bundled zint.exe, not downloaded from an untrusted source, so we
# disable Pillow's decompression-bomb guard rather than have it reject a
# legitimate barcode before the shrink loop gets a chance to run.
Image.MAX_IMAGE_PIXELS = None


# ---------------------------------------------------------------------------
# Symbology definitions
#
# X-dimension (module/bar width) values are sourced from the GS1 General
# Specifications (section 5.12.3.1, "Minimum symbol quality specification
# tables"):
#   - GS1-128 (linear):        nominal 0.330mm / minimum X 0.264mm (0.80x)
#   - GS1 DataMatrix:          GS1 requires an X-dim >= 1.5x the linear
#                              minimum -> nominal 0.495mm, minimum 0.255mm,
#                              maximum 0.990mm
#   - GS1 QR Code:             nominal 0.495mm, minimum 0.396mm (0.80x),
#                              maximum 0.990mm
#   - QR Code (Digital Link):  same module-size guidance as GS1 QR Code
# ---------------------------------------------------------------------------

SYMBOLOGIES = {
    "GS1-128": {
        "zint_id": 16,
        "use_gs1": True,
        "has_native_hri": True,   # Zint draws HRI text natively for GS1-128
        "x_dim_min": 0.264,
        "x_dim_nominal": 0.330,
        "x_dim_max": 0.660,
    },
    "GS1 DataMatrix": {
        "zint_id": 71,
        "use_gs1": True,
        "has_native_hri": False,
        "x_dim_min": 0.255,
        "x_dim_nominal": 0.495,
        "x_dim_max": 0.990,
    },
    "GS1 QR Code": {
        "zint_id": 58,
        "use_gs1": True,
        "has_native_hri": False,
        "x_dim_min": 0.396,
        "x_dim_nominal": 0.495,
        "x_dim_max": 0.990,
    },
    "QR Code (GS1 Digital Link)": {
        "zint_id": 58,
        "use_gs1": False,  # payload is already a plain URI, not bracketed AI
        "has_native_hri": False,
        "x_dim_min": 0.396,
        "x_dim_nominal": 0.495,
        "x_dim_max": 0.990,
    },
}

DEFAULT_SYMBOLOGY = "GS1-128"
DEFAULT_BAR_HEIGHT_MM = 18.0
ABSOLUTE_MIN_X_DIM_MM = 0.15  # last-resort floor if even the GS1 min doesn't fit

TEXT_SUPERSAMPLE = 4


# ---------------------------------------------------------------------------
# zint.exe location
# ---------------------------------------------------------------------------

def find_zint_exe():
    """
    Locates the bundled zint.exe:
      - Next to this script / bundled by PyInstaller (sys._MEIPASS-aware)
      - Falls back to PATH
    """
    candidates = []

    if getattr(sys, "frozen", False) and hasattr(sys, "_MEIPASS"):
        candidates.append(os.path.join(sys._MEIPASS, "bin", "zint.exe"))

    base_dir = os.path.dirname(os.path.abspath(__file__))
    candidates.append(os.path.join(base_dir, "bin", "zint.exe"))
    candidates.append(os.path.join(base_dir, "zint.exe"))

    for c in candidates:
        if os.path.isfile(c):
            return c

    # Fall back to PATH
    import shutil
    found = shutil.which("zint") or shutil.which("zint.exe")
    if found:
        return found

    raise FileNotFoundError(
        "Could not locate zint.exe. Expected it bundled under bin/zint.exe."
    )


def _mm_to_px(mm, dpi):
    return int(round(mm / 25.4 * dpi))


# ---------------------------------------------------------------------------
# Zint invocation
# ---------------------------------------------------------------------------

def _run_zint(data, zint_exe, out_path, x_dim_mm, bar_height_mm, dpi,
              zint_id, use_gs1):
    cmd = [
        zint_exe,
        "-b", str(zint_id),
        "-d", data,
        "-o", out_path,
        "--scalexdimdp={:.3f}mm,{}dpi".format(round(x_dim_mm, 3), dpi),
        "--quietzones",
    ]
    if use_gs1:
        cmd.extend(["--gs1", "--gs1parens"])

    # --height is expressed in X-dimension multiples for linear symbols;
    # for 2D symbols zint sizes the whole symbol from the module count, so
    # --height is not meaningful there and is omitted.
    if zint_id == 16:  # GS1-128 (linear)
        x_dim_multiples = max(1, int(round(bar_height_mm / x_dim_mm)))
        cmd.extend(["--height", str(x_dim_multiples)])

    result = subprocess.run(
        cmd,
        capture_output=True,
        text=True,
        timeout=30,
    )
    if result.returncode != 0:
        raise RuntimeError(
            f"zint failed (exit {result.returncode}): {result.stderr.strip() or result.stdout.strip()}"
        )
    if not os.path.isfile(out_path):
        raise RuntimeError("zint reported success but produced no output file")


def generate_barcode_image(data, zint_exe, tmp_dir, dpi=300, max_width_px=None,
                            bar_height_mm=DEFAULT_BAR_HEIGHT_MM,
                            symbology=DEFAULT_SYMBOLOGY, x_dim_mm=None):
    """
    Renders the barcode for `data` using the given symbology.

    If the rendered symbol would exceed `max_width_px`, the X-dimension is
    shrunk in small steps toward the symbology's own GS1-specified minimum
    (never below it) until it fits, or until the minimum is reached (in
    which case a warning is returned alongside the image).

    Returns: (PIL.Image, warning_str_or_None)
    """
    if symbology not in SYMBOLOGIES:
        raise ValueError(f"Unknown symbology: {symbology!r}")
    sym = SYMBOLOGIES[symbology]

    warning = None
    requested_x_dim = x_dim_mm if x_dim_mm else sym["x_dim_nominal"]

    if requested_x_dim < sym["x_dim_min"] - 1e-9 or requested_x_dim > sym["x_dim_max"] + 1e-9:
        warning = (
            f"Module size {requested_x_dim:.3f}mm is outside the GS1-specified "
            f"range for {symbology} ({sym['x_dim_min']:.3f}-{sym['x_dim_max']:.3f}mm)."
        )

    current_x_dim = requested_x_dim
    out_path = os.path.join(tmp_dir, "barcode.bmp")

    for attempt in range(25):
        _run_zint(data, zint_exe, out_path, current_x_dim, bar_height_mm, dpi,
                  sym["zint_id"], sym["use_gs1"])
        img = Image.open(out_path)
        img.load()

        if max_width_px is None or img.width <= max_width_px:
            return img, warning

        # Too wide: shrink toward the symbology minimum
        floor = min(sym["x_dim_min"], ABSOLUTE_MIN_X_DIM_MM)
        if current_x_dim <= floor + 1e-9:
            warning = (
                (warning + " " if warning else "") +
                f"Barcode does not fit within the label even at the minimum "
                f"X-dimension ({floor:.3f}mm) for {symbology}; it will be clipped "
                f"or overflow slightly."
            )
            return img, warning

        current_x_dim = max(floor, current_x_dim * 0.92)

    return img, warning


# ---------------------------------------------------------------------------
# Text rendering (supersampled to survive black/white print thresholding)
# ---------------------------------------------------------------------------

def _load_font(size):
    candidates = [
        "arial.ttf", "Arial.ttf",
        "segoeui.ttf",
        "/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf",
        "DejaVuSans.ttf",
    ]
    for name in candidates:
        try:
            return ImageFont.truetype(name, size)
        except (OSError, IOError):
            continue
    return ImageFont.load_default()


def _render_text_image(text, font_size, font_loader=_load_font):
    """
    Renders `text` at TEXT_SUPERSAMPLE x the requested font size, then
    downsamples with LANCZOS. This anti-aliases the glyph edges through
    real gray levels that survive the print pipeline's hard black/white
    threshold, instead of collapsing to jagged text at native resolution.
    """
    big_size = font_size * TEXT_SUPERSAMPLE
    font = font_loader(big_size)

    tmp_img = Image.new("L", (10, 10), 255)
    tmp_draw = ImageDraw.Draw(tmp_img)
    bbox = tmp_draw.textbbox((0, 0), text, font=font)
    w = max(1, bbox[2] - bbox[0])
    h = max(1, bbox[3] - bbox[1])

    pad = big_size // 4
    big_img = Image.new("L", (w + pad * 2, h + pad * 2), 255)
    big_draw = ImageDraw.Draw(big_img)
    big_draw.text((pad - bbox[0], pad - bbox[1]), text, font=font, fill=0)

    small_w = max(1, (w + pad * 2) // TEXT_SUPERSAMPLE)
    small_h = max(1, (h + pad * 2) // TEXT_SUPERSAMPLE)
    small_img = big_img.resize((small_w, small_h), Image.LANCZOS)
    return small_img


def _text_width(draw, text, font):
    bbox = draw.textbbox((0, 0), text, font=font)
    return bbox[2] - bbox[0]


def _break_long_token(draw, token, font, max_width):
    """
    Character-level fallback for a single "word" (no spaces) that is
    itself wider than max_width -- GS1 element strings and URIs have no
    spaces, so plain word-wrap can't break them and would otherwise
    overflow the label. Splits `token` into as-long-as-possible chunks
    that each fit max_width.
    """
    if _text_width(draw, token, font) <= max_width:
        return [token]

    chunks = []
    current = ""
    for ch in token:
        trial = current + ch
        if current and _text_width(draw, trial, font) > max_width:
            chunks.append(current)
            current = ch
        else:
            current = trial
    if current:
        chunks.append(current)
    return chunks


def _wrap_text(draw, text, font, max_width):
    words = text.split()
    if not words:
        return []
    lines = []
    current = ""
    for word in words:
        # A single "word" wider than the available width (e.g. an
        # unbroken GS1 element string or URI) is split at the character
        # level so it still fits, instead of overflowing the label.
        if _text_width(draw, word, font) > max_width:
            if current:
                lines.append(current)
                current = ""
            lines.extend(_break_long_token(draw, word, font, max_width))
            continue

        trial = word if not current else current + " " + word
        if _text_width(draw, trial, font) <= max_width:
            current = trial
        else:
            lines.append(current)
            current = word
    if current:
        lines.append(current)
    return lines


def _wrapped_text_image(text, font_size, max_width_px, font_loader=_load_font):
    """Wraps `text` to `max_width_px` at native size, then renders each
    line supersampled and stacks them into one image."""
    probe_font = font_loader(font_size)
    probe_img = Image.new("L", (10, 10))
    probe_draw = ImageDraw.Draw(probe_img)
    lines = _wrap_text(probe_draw, text, probe_font, max_width_px)

    line_imgs = [_render_text_image(line, font_size, font_loader) for line in lines]
    if not line_imgs:
        return Image.new("L", (1, 1), 255)

    width = max(im.width for im in line_imgs)
    spacing = max(2, font_size // 6)
    total_height = sum(im.height for im in line_imgs) + spacing * (len(line_imgs) - 1)

    out = Image.new("L", (width, total_height), 255)
    y = 0
    for im in line_imgs:
        x = (width - im.width) // 2
        out.paste(im, (x, y))
        y += im.height + spacing
    return out


# ---------------------------------------------------------------------------
# Label composition
# ---------------------------------------------------------------------------

def compose_label(barcode_bmp, header_text, footer_text, out_path, dpi=300,
                   width_in=3.0, height_in=3.0, data_text=None):
    """
    Composites header text (optional), the barcode, human-readable data
    text (optional, only meaningful for symbologies lacking native HRI),
    and footer text (optional) onto a canvas sized to width_in x height_in
    at `dpi`, centered as one group both horizontally and vertically.
    """
    canvas_w = _mm_to_px(width_in * 25.4, dpi)
    canvas_h = _mm_to_px(height_in * 25.4, dpi)
    canvas = Image.new("RGB", (canvas_w, canvas_h), "white")

    margin = max(4, min(canvas_w, canvas_h) // 40)
    max_content_w = canvas_w - margin * 2

    # Physically-grounded minimum font sizes (px), not just a fraction of
    # the canvas -- pure pixel-fraction sizing produced illegibly small
    # text on small/low-DPI labels.
    header_footer_size = max(_mm_to_px(2.5, dpi), min(canvas_w, canvas_h) // 22)
    data_text_size = max(_mm_to_px(2.0, dpi), min(canvas_w, canvas_h) // 34)

    blocks = []  # list of PIL images to stack vertically, centered

    if header_text and header_text.strip():
        blocks.append(_wrapped_text_image(header_text.strip(), header_footer_size, max_content_w))

    # Fit barcode width to the canvas without ever upscaling it beyond its
    # rendered size (generate_barcode_image already handled shrinking to
    # fit width; here we only downscale further if still too tall/wide).
    bc = barcode_bmp
    if bc.width > max_content_w:
        scale = max_content_w / bc.width
        bc = bc.resize((max_content_w, max(1, int(bc.height * scale))), Image.LANCZOS)
    blocks.append(bc.convert("RGB"))

    if data_text and data_text.strip():
        blocks.append(_wrapped_text_image(data_text.strip(), data_text_size, max_content_w).convert("RGB"))

    if footer_text and footer_text.strip():
        blocks.append(_wrapped_text_image(footer_text.strip(), header_footer_size, max_content_w).convert("RGB"))

    spacing = max(3, min(canvas_w, canvas_h) // 50)
    total_h = sum(b.height for b in blocks) + spacing * (len(blocks) - 1)
    y = max(margin, (canvas_h - total_h) // 2)

    draw_canvas = canvas
    for b in blocks:
        x = (canvas_w - b.width) // 2
        draw_canvas.paste(b, (x, y))
        y += b.height + spacing

    draw_canvas.save(out_path)
    return out_path


def generate_label_for_row(gs1_data, header_text, footer_text, zint_exe, out_path,
                            dpi=300, width_in=3.0, height_in=3.0,
                            symbology=DEFAULT_SYMBOLOGY, x_dim_mm=None):
    """
    Top-level convenience wrapper: renders the barcode for `gs1_data` and
    composes the full label (header/barcode/HRI-if-needed/footer) to
    `out_path`. Returns (out_path, warning_or_None).
    """
    sym = SYMBOLOGIES.get(symbology, SYMBOLOGIES[DEFAULT_SYMBOLOGY])

    with tempfile.TemporaryDirectory() as tmp_dir:
        canvas_w_px = _mm_to_px(width_in * 25.4, dpi)
        margin = max(4, min(canvas_w_px, _mm_to_px(height_in * 25.4, dpi)) // 40)
        max_barcode_width_px = canvas_w_px - margin * 2

        barcode_img, warning = generate_barcode_image(
            gs1_data, zint_exe, tmp_dir, dpi=dpi,
            max_width_px=max_barcode_width_px,
            symbology=symbology, x_dim_mm=x_dim_mm,
        )

        data_text = None if sym["has_native_hri"] else gs1_data

        compose_label(
            barcode_img, header_text, footer_text, out_path,
            dpi=dpi, width_in=width_in, height_in=height_in,
            data_text=data_text,
        )

    return out_path, warning
